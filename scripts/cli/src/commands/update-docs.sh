# list of CLI reference pages, indexed by the search plugin of the documentation website (see docs/index.html)
{
  echo "// generated by 'playground update-docs' in https://github.com/vdesabou/kafka-docker-playground: list of CLI reference pages, indexed by the search plugin"
  echo "window.KDP_CLI_PAGES = ["
  ls ${root_folder}/scripts/cli/docs | grep '^playground .*\.md$' | sed -e 's/\.md$//' -e 's/ /%20/g' -e 's#.*#  "/&",#'
  echo "];"
} > ${root_folder}/docs/cli-pages.js

mv ${root_folder}/scripts/cli/docs/* ${root_folder}/docs/

