# ── HTML parsing ──────────────────────────────────────────────────────────────

class _ReportParser(HTMLParser):
    """Collects the <h3> sections of the report, each with its tables (header row + data rows)."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.sections: Dict[str, List[List[List[str]]]] = {}
        self.text_after_tables: List[str] = []
        self._section: Optional[str] = None
        self._in = None  # "title" | "h3" | "cell"
        self._buf: List[str] = []
        self._table: Optional[List[List[str]]] = None
        self._row: Optional[List[str]] = None

    def handle_starttag(self, tag, attrs):
        if tag == "title":
            self._in, self._buf = "title", []
        elif tag == "h3":
            self._in, self._buf = "h3", []
        elif tag == "table":
            self._table = []
        elif tag == "tr" and self._table is not None:
            self._row = []
        elif tag in ("td", "th") and self._row is not None:
            self._in, self._buf = "cell", []
        elif tag == "br" and self._in == "cell":
            self._buf.append(" ")

    def handle_endtag(self, tag):
        if tag == "title" and self._in == "title":
            self.title, self._in = "".join(self._buf).strip(), None
        elif tag == "h3" and self._in == "h3":
            self._section, self._in = " ".join("".join(self._buf).split()), None
            self.sections.setdefault(self._section, [])
        elif tag in ("td", "th") and self._in == "cell":
            self._row.append(" ".join("".join(self._buf).split()))
            self._in = None
        elif tag == "tr" and self._row is not None:
            if self._row:
                self._table.append(self._row)
            self._row = None
        elif tag == "table" and self._table is not None:
            if self._section is not None and self._table:
                self.sections[self._section].append(self._table)
            elif self._table:
                self.text_after_tables.append(" ".join(c for r in self._table for c in r))
            self._table = None

    def handle_data(self, data):
        if self._in in ("title", "h3", "cell"):
            self._buf.append(data)
        elif data.strip():
            self.text_after_tables.append(data.strip())


class Report:
    def __init__(self, path: str):
        self.path = path
        with open(path, encoding="utf-8", errors="replace") as f:
            content = f.read()
        p = _ReportParser()
        p.feed(content)
        self.title = p.title
        # section -> list of tables, each table a list of row dicts keyed by column heading
        self.tables: Dict[str, List[List[Dict[str, str]]]] = {}
        footer = ""
        for section, tables in p.sections.items():
            parsed = []
            for t in tables:
                header, rows = t[0], t[1:]
                if len(header) == 1 and header[0].startswith("Report generated on instance"):
                    footer = header[0]
                    continue
                parsed.append([dict(zip(header, r)) for r in rows])
            self.tables[section] = parsed
        if not footer:
            footer = next((t for t in p.text_after_tables if "Report generated on instance" in t), "")
        m = re.search(r"Report generated on instance:\s*(\S+)\s+at time:\s*([\d-]+ [\d:]+)", footer)
        self.instance = m.group(1) if m else None
        self.generated = _parse_time(m.group(2)) if m else None
        if self.generated is None:
            m = re.search(r"orclcdc_diag_(\d{8}_\d{4})", os.path.basename(path))
            if m:
                self.generated = datetime.strptime(m.group(1), "%Y%m%d_%H%M")

    def is_diag_report(self) -> bool:
        return "XStream" in self.title and "Diagnostics" in self.title and bool(self.tables)

    def rows(self, section: str, index: int = 0) -> List[Dict[str, str]]:
        tables = self.tables.get(section, [])
        return tables[index] if len(tables) > index else []

    def all_rows(self, section: str) -> List[Dict[str, str]]:
        return [r for t in self.tables.get(section, []) for r in t]

    def has_section(self, section: str) -> bool:
        return section in self.tables


# ── value helpers ─────────────────────────────────────────────────────────────

def _num(value) -> Optional[float]:
    if value is None:
        return None
    v = str(value).strip().replace(",", "")
    try:
        return float(v)
    except ValueError:
        return None


def _parse_time(value) -> Optional[datetime]:
    if not value:
        return None
    v = str(value).strip()
    for fmt in ("%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%d %H:%M:%S", "%d-%b-%y %I.%M.%S.%f %p", "%d-%b-%y %H:%M:%S", "%d-%b-%y"):
        try:
            return datetime.strptime(v[:26] if "%f" in fmt else v, fmt)
        except ValueError:
            continue
    return None


def _fmt_num(v) -> str:
    n = _num(v)
    if n is None:
        return str(v) if v not in (None, "") else "-"
    return f"{int(n):,}" if n == int(n) else f"{n:,.2f}"


def _fmt_seconds(s: Optional[float]) -> str:
    if s is None:
        return "-"
    s = int(s)
    if s < 120:
        return f"{s}s"
    if s < 7200:
        return f"{s // 60}m{s % 60:02d}s"
    if s < 172800:
        return f"{s // 3600}h{(s % 3600) // 60:02d}m"
    return f"{s // 86400}d{(s % 86400) // 3600:02d}h"


def _fmt_evidence(ev) -> str:
    """key=value pairs of a finding's evidence, lists joined."""
    if not isinstance(ev, dict):
        return "" if ev is None else str(ev)

    def val(v):
        if isinstance(v, (list, tuple, set)):
            return ", ".join(str(x) for x in v)
        return _fmt_num(v) if isinstance(v, (int, float)) else str(v)
    return "  ".join(f"{k}={val(v)}" for k, v in ev.items() if v not in (None, "", []))


def _error(number, message) -> str:
    """ORA-01291: missing logfile, whether the message already starts with ORA- or not."""
    message = (message or "").strip()
    if message.startswith("ORA-") or not number:
        return message or (f"ORA-{int(_num(number)):05d}" if _num(number) is not None else "")
    n = _num(number)
    return f"ORA-{int(n):05d}: {message}" if n is not None else f"{number} {message}".strip()


def _col(row: Dict[str, str], *names) -> Optional[str]:
    """Value of the first column present (headings changed between versions of the script)."""
    for n in names:
        if n in row and row[n] != "":
            return row[n]
    return None


# ── analysis ──────────────────────────────────────────────────────────────────

class Analysis:
    def __init__(self, report: Report, top: int):
        self.r = report
        self.top = top
        self.findings: List[dict] = []
        self.summary: Dict[str, object] = {}
        self.prerequisites: List[dict] = []
        self.patterns: Dict[str, List[str]] = {}
        self.problem: Optional[dict] = None

    def add(self, severity, section, message, evidence=None, pattern=None, action=None):
        f = {"severity": severity, "section": section, "message": message}
        if evidence:
            f["evidence"] = evidence
        if action:
            f["action"] = action
        if pattern:
            f["pattern"] = pattern
            self.patterns.setdefault(pattern, []).append(message)
        self.findings.append(f)

    def max_sga(self, section, name_col, name) -> Optional[float]:
        """MAX_SGA_SIZE of a component in MB, None when INFINITE or not in the report."""
        for r in self.r.rows(section):
            if r.get(name_col) == name and r.get("Parameter Name") == "MAX_SGA_SIZE":
                return _num(r.get("Parameter Value"))
        return None

    def apply_param(self, name, parameter) -> Optional[float]:
        for r in self.r.rows("Apply: Parameters"):
            if r.get("Apply Name") == name and r.get("Parameter Name") == parameter:
                return _num(r.get("Parameter Value"))
        return None

    def age_seconds(self, value) -> Optional[float]:
        t = _parse_time(value)
        if t is None or self.r.generated is None:
            return None
        return (self.r.generated - t).total_seconds()

    def scn_time(self, scn) -> Optional[datetime]:
        """Time of an SCN, interpolated in the registered log file that contains it (None when no log contains it)."""
        scn = _num(scn)
        if not scn:
            return None
        for r in self.r.rows("Capture Process: Registered log files"):
            a, b = _num(r.get("First SCN")), _num(r.get("Next SCN"))
            ta, tb = _parse_time(r.get("First Time")), _parse_time(r.get("Next Time"))
            if None in (a, b, ta, tb) or not a <= scn < b:
                continue
            return ta + (tb - ta) * ((scn - a) / (b - a))
        return None

    def run(self):
        self.overview()
        self.capture()
        self.logminer()
        self.outbound()
        self.apply()
        self.queue_and_pool()
        self.transactions()
        self.rules()
        self.downstream()
        self.alerts_and_events()
        self.sessions()
        order = {s: i for i, s in enumerate(SEVERITIES)}
        self.findings.sort(key=lambda f: order[f["severity"]])
        return self

    # Overview + prerequisites
    def overview(self):
        db = (self.r.rows("Overview: Database") or [{}])[0]
        params = {}
        for row in self.r.rows("Overview: Initialization parameters"):
            params.setdefault(row.get("Parameter Name", ""), row.get("Parameter Value", ""))
        version = (self.r.rows("Overview: Database Version") or [{}])[0].get("Version Banner")
        self.summary["database"] = {
            "name": db.get("DB Name"), "unique_name": db.get("Unique DB Name"),
            "global_name": (self.r.rows("Overview: Global database name") or [{}])[0].get("Global DB Name"),
            "role": db.get("DB Role"), "open_mode": db.get("Open Mode"), "cdb": db.get("CDB"),
            "platform": db.get("Platform Name"), "version": version, "current_scn": db.get("Current SCN"),
            "instance": self.r.instance,
        }
        self.summary["parameters"] = params
        self.current_scn = _num(db.get("Current SCN"))

        def prereq(check, value, status, note=""):
            self.prerequisites.append({"check": check, "value": value if value not in (None, "") else "NOT PRESENT IN REPORT",
                                       "status": status, "note": note})

        log_mode = db.get("Log Mode")
        if log_mode is None:
            prereq("ARCHIVELOG mode", None, "UNKNOWN")
        elif log_mode == "ARCHIVELOG":
            prereq("ARCHIVELOG mode", log_mode, "PASS")
        else:
            prereq("ARCHIVELOG mode", log_mode, "FAIL")
            self.add("CRITICAL", "Overview: Database", f"Database is in {log_mode} mode: XStream needs ARCHIVELOG",
                     {"Log Mode": log_mode}, "G", "SHUTDOWN IMMEDIATE; STARTUP MOUNT; ALTER DATABASE ARCHIVELOG; ALTER DATABASE OPEN;")

        sup_min = db.get("Supplemental Log (MIN)")
        if sup_min is None:
            prereq("Minimal supplemental logging", None, "UNKNOWN")
        elif sup_min in ("YES", "IMPLICIT"):
            prereq("Minimal supplemental logging", sup_min, "PASS")
        else:
            prereq("Minimal supplemental logging", sup_min, "FAIL")
            self.add("CRITICAL", "Overview: Database", "Minimal supplemental logging is not enabled",
                     {"Supplemental Log (MIN)": sup_min}, "G", "ALTER DATABASE ADD SUPPLEMENTAL LOG DATA;")
        sup_all = db.get("Supplemental Log (ALL)")
        if sup_all is not None:
            prereq("Database-level ALL column supplemental logging", sup_all, "PASS" if sup_all == "YES" else "CHECK",
                   "" if sup_all == "YES" else "table-level ALL COLUMNS logging is then required on every captured table (not collected by the report)")

        sp = params.get("streams_pool_size")
        sga_target = _num(params.get("sga_target"))
        memory_target = _num(params.get("memory_target"))
        if sp is None:
            prereq("streams_pool_size", None, "UNKNOWN")
        elif _num(sp) == 0:
            auto = (sga_target or 0) > 0 or (memory_target or 0) > 0
            prereq("streams_pool_size", sp, "WARNING", "auto-managed by " + ("sga_target/memory_target" if auto else "nothing"))
            self.add("HIGH" if not auto else "MEDIUM", "Overview: Initialization parameters",
                     "streams_pool_size is not set explicitly" + ("" if auto else " and no automatic memory management is configured"),
                     {"streams_pool_size": sp, "sga_target": params.get("sga_target"), "memory_target": params.get("memory_target")},
                     "A", "ALTER SYSTEM SET streams_pool_size=<size, see Streams Pool: Size advice> SCOPE=BOTH;")
        else:
            prereq("streams_pool_size", f"{_fmt_num(_num(sp) / 1024 / 1024)} MB" if _num(sp) else sp, "PASS")
        pga = params.get("pga_aggregate_target")
        prereq("pga_aggregate_target", f"{_fmt_num(_num(pga) / 1024 / 1024)} MB" if _num(pga) else pga, "INFO")
        for comp, section in (("capture", "Capture Process: Parameters"), ("apply (outbound)", "Apply: Parameters")):
            values = [r.get("Parameter Value") for r in self.r.rows(section) if r.get("Parameter Name") == "MAX_SGA_SIZE"]
            if not self.r.rows(section):
                prereq(f"MAX_SGA_SIZE ({comp})", None, "UNKNOWN")
            else:
                v = ", ".join(sorted(set(v for v in values if v))) or None
                prereq(f"MAX_SGA_SIZE ({comp})", v, "INFO" if v != "INFINITE" else "CHECK",
                       "INFINITE: bounded only by the streams pool" if v == "INFINITE" else "")
        role = db.get("DB Role")
        if role and role != "PRIMARY":
            self.add("INFO", "Overview: Database", f"Database role is {role} (downstream capture setup?)", {"DB Role": role})

    # Capture
    def capture(self):
        general = self.r.rows("Capture Process: General")
        status = self.r.rows("Capture Process: Status")
        stats = self.r.rows("Capture Process: Statistics", 0)
        stats2 = {r.get("Capture Name"): r for r in self.r.rows("Capture Process: Statistics", 1)}
        captures = []
        names = [r.get("Capture Name") for r in general] or [r.get("Capture Name") for r in status]
        if self.r.has_section("Capture Process: General") and not names:
            self.add("CRITICAL", "Capture Process: General", "No XStream Out capture process in the database",
                     None, "H", "Create the XStream outbound server (DBMS_XSTREAM_ADM.CREATE_OUTBOUND) as described in the connector prerequisites")
        status_by = {r.get("Capture Name"): r for r in status}
        stats_by = {r.get("Capture Name"): r for r in stats}
        for name in names:
            st, sx, s2 = status_by.get(name, {}), stats_by.get(name, {}), stats2.get(name, {})
            latency = _num(sx.get("Capture Latency (seconds)"))
            captured_scn = _num(st.get("Captured SCN"))
            cap = {
                "name": name, "status": st.get("Status"), "state": sx.get("State"),
                "outbound": st.get("Outbound Name"), "outbound_status": st.get("Outbound Status"),
                "start_scn": st.get("Start SCN"), "captured_scn": st.get("Captured SCN"), "applied_scn": st.get("Applied SCN"),
                "required_checkpoint_scn": st.get("Required Checkpoint SCN"),
                "latency_seconds": latency, "redo_mined_mb": _num(sx.get("Redo Mined (MB)")),
                "sga_used_mb": _num(sx.get("SGA Used (MB)")), "sga_allocated_mb": _num(sx.get("SGA Allocated (MB)")),
                "messages_captured": _num(s2.get("Total Messages Captured")),
                "messages_enqueued": _num(s2.get("Total Messages Enqueued")),
                "last_captured_time": s2.get("Last Captured Message Time"),
                "startup_time": sx.get("Startup Time"),
                "scn_gap": (self.current_scn - captured_scn) if self.current_scn and captured_scn else None,
                "state_change_time": sx.get("State Change Time"),
                "last_redo_flushed_time": s2.get("Last Redo Flushed Time"),
            }
            # captured SCN as a time: where the capture really is, latency is often empty when nothing is captured
            pos = self.scn_time(captured_scn)
            cap["captured_scn_time"] = pos.strftime("%Y-%m-%d %H:%M:%S") if pos else None
            cap["position_age_seconds"] = (self.r.generated - pos).total_seconds() if pos and self.r.generated else None
            captures.append(cap)
            section = "Capture Process: Status"
            if cap["status"] and cap["status"] != "ENABLED":
                err = _error(st.get("Error Number"), st.get("Error Message"))
                self.add("CRITICAL", section, f"Capture {name} is {cap['status']}" + (f": {err}" if err else ""),
                         {"Status": cap["status"], "Error Number": st.get("Error Number"), "Error Message": st.get("Error Message")},
                         "H", f"Fix the error, then EXEC DBMS_CAPTURE_ADM.START_CAPTURE('{name}');")
            state = cap["state"] or ""
            if "FLOW CONTROL" in state:
                self.add("HIGH", "Capture Process: Statistics", f"Capture {name} is {state}: the outbound server / connector does not consume fast enough",
                         {"State": state}, "C")
            elif state and state != "CAPTURING CHANGES" and not state.startswith("WAITING FOR TRANSACTION") \
                    and not state.startswith("WAITING FOR REDO"):
                self.add("MEDIUM", "Capture Process: Statistics", f"Capture {name} state is {state}", {"State": state})
            self.redo_wait(cap)
            if latency is not None:
                ev = {"Capture Latency (seconds)": _fmt_num(latency), "Last Captured Message Time": cap["last_captured_time"],
                      "Captured SCN": cap["captured_scn"], "Current SCN": self.summary["database"]["current_scn"]}
                idle = state.startswith("WAITING FOR REDO") and not cap.get("stuck")
                if latency > LATENCY_CRIT:
                    self.add("INFO" if idle else "CRITICAL", "Capture Process: Statistics",
                             f"Capture {name} latency is {_fmt_seconds(latency)}" + (" while WAITING FOR REDO (idle database: no backlog)" if idle else " (> 300s)"), ev)
                elif latency > LATENCY_WARN:
                    self.add("INFO" if idle else "HIGH", "Capture Process: Statistics",
                             f"Capture {name} latency is {_fmt_seconds(latency)}" + (" while WAITING FOR REDO" if idle else " (> 60s)"), ev)
            # SGA is allocated on demand: only the use of a finite MAX_SGA_SIZE means memory pressure
            used = cap["sga_used_mb"]
            max_sga = self.max_sga("Capture Process: Parameters", "Capture Name", name)
            cap["max_sga_size_mb"] = max_sga
            if used is not None and max_sga:
                pct = used * 100 / max_sga
                cap["sga_used_pct"] = round(pct, 1)
                if pct > SGA_USED_CRIT:
                    self.add("HIGH", "Capture Process: Statistics", f"Capture {name} uses {pct:.0f}% of its MAX_SGA_SIZE",
                             {"SGA Used (MB)": _fmt_num(used), "MAX_SGA_SIZE (MB)": _fmt_num(max_sga)}, "A",
                             f"EXEC DBMS_CAPTURE_ADM.SET_PARAMETER('{name}', 'max_sga_size', '<MB>'); and size streams_pool_size accordingly")
            applied = _num(cap["applied_scn"])
            if captured_scn and applied and captured_scn - applied > 0:
                cap["applied_scn_gap"] = captured_scn - applied
                self.add("INFO", "Capture Process: Status",
                         f"Applied SCN of {name} is {_fmt_num(captured_scn - applied)} SCNs behind the captured SCN: "
                         "after a restart, capture mines redo again from the applied SCN, and the logs from there must be kept",
                         {"Captured SCN": cap["captured_scn"], "Applied SCN": cap["applied_scn"], "Status Change Time": st.get("Status Change Time")})
            c, e = cap["messages_captured"], cap["messages_enqueued"]
            if c and e is not None and c > 1000 and e < c * 0.5:
                self.add("INFO", "Capture Process: Statistics",
                         f"Capture {name} enqueued {_fmt_num(e)} of {_fmt_num(c)} captured messages (filtered by rules, or staging bottleneck)",
                         {"Total Messages Captured": _fmt_num(c), "Total Messages Enqueued": _fmt_num(e)})
        self.summary["captures"] = captures
        logs = self.r.rows("Capture Process: Registered log files")
        if logs:
            not_purgeable = [r for r in logs if r.get("Purgeable") == "NO"]
            threads = []
            for thread in sorted({r.get("Thread") for r in logs}, key=lambda t: _num(t) or 0):
                rows = [r for r in logs if r.get("Thread") == thread and _num(r.get("Sequence")) is not None]
                seqs = sorted({int(_num(r["Sequence"])) for r in rows})
                if not seqs:
                    continue
                threads.append({"thread": thread, "first_sequence": seqs[0], "last_sequence": seqs[-1],
                                "newest_next_time": max((r.get("Next Time") or "" for r in rows), default=None) or None,
                                "missing_sequences": [[a + 1, b - 1] for a, b in zip(seqs, seqs[1:]) if b > a + 1]})
            self.summary["registered_logs"] = {"total": len(logs), "not_purgeable": len(not_purgeable),
                                               "oldest_needed": min((r.get("First Time") or "" for r in not_purgeable), default=None),
                                               "newest": max((r.get("Next Time") or "" for r in logs), default=None) or None,
                                               "threads": threads}

    def redo_wait(self, cap):
        """WAITING FOR REDO is idle on a quiet database, but not when the redo it waits for is old: the log is gone or unreadable."""
        m = REDO_WAIT.search(cap["state"] or "")
        if not m:
            return
        name = cap["name"]
        scn = m.group("scn")
        wait = {"file": m.group("file").strip(), "thread": m.group("thread"), "sequence": m.group("sequence"),
                "scn": (int(scn, 16) if scn.lower().startswith("0x") else int(scn)) if scn else None}
        log = next((r for r in self.r.rows("Capture Process: Registered log files")
                    if r.get("Thread") == wait["thread"] and r.get("Sequence") == wait["sequence"]), None)
        wait["registered"] = log is not None
        wait["archived"] = bool(log and _num(log.get("Next SCN")))
        if log:
            wait["first_time"], wait["next_time"] = log.get("First Time"), log.get("Next Time")
        cap["waiting_for_redo"] = wait
        age = cap["position_age_seconds"]
        ev = {"State": cap["state"], "State Change Time": cap["state_change_time"], "Startup Time": cap["startup_time"],
              "Captured SCN": cap["captured_scn"], "Captured SCN time": cap["captured_scn_time"],
              "behind the report": _fmt_seconds(age) if age is not None else None,
              "Current SCN": self.summary["database"]["current_scn"], "SCN gap": _fmt_num(cap["scn_gap"]),
              "Total Messages Captured": _fmt_num(cap["messages_captured"]), "Last Redo Flushed Time": cap["last_redo_flushed_time"]}
        since = f" since {cap['state_change_time']}" if cap["state_change_time"] else ""
        position = f" Captured SCN {_fmt_num(cap['captured_scn'])} ≈ {cap['captured_scn_time']} ({_fmt_seconds(age)} before the report)" if age is not None else ""
        action = (f"[DBA] check that the file still exists and is readable from the instance running the capture: "
                  f"SELECT thread#, sequence#, name, status, deleted, first_time FROM v$archived_log WHERE thread# = {wait['thread']} "
                  f"AND sequence# >= {wait['sequence']} ORDER BY sequence#; and the alert log of that instance (ORA-00308, ORA-01291). "
                  f"Restore it and the following logs of every thread from the backup (RMAN> RESTORE ARCHIVELOG FROM SEQUENCE {wait['sequence']} "
                  f"THREAD {wait['thread']};): the capture resumes on its own. If the logs are gone for good, the capture cannot resume from "
                  "this position: recreate the outbound server and take a new snapshot. Then keep archived logs until the capture has mined "
                  "them (RMAN keeps them, RMAN-08137, unless DELETE ... FORCE, deletion outside RMAN or FRA space pressure)")
        # a complete archived log is readable at once: still waiting for it a minute later means it cannot be read
        waiting = self.age_seconds(cap["state_change_time"])
        if wait["archived"] and (waiting is None or waiting > LATENCY_WARN):
            cap["stuck"] = True
            self.add("CRITICAL", "Capture Process: Statistics",
                     f"Capture {name} is WAITING FOR REDO{since} on archived log thread {wait['thread']} sequence {wait['sequence']} "
                     f"({wait.get('first_time')} → {wait.get('next_time')}), already registered and complete: the capture cannot read it "
                     f"(deleted, or not readable from the capture instance) and captures nothing.{position}",
                     dict(ev, **{"waiting for file": wait["file"]}), "I", action)
        elif age is not None and age > POSITION_STALE_SECONDS:
            cap["stuck"] = True
            self.add("HIGH", "Capture Process: Statistics",
                     f"Capture {name} is WAITING FOR REDO{since} on thread {wait['thread']} sequence {wait['sequence']} "
                     f"while its position is {_fmt_seconds(age)} old: the redo after it is not available to the capture.{position}",
                     dict(ev, **{"waiting for file": wait["file"]}), "I", action)

