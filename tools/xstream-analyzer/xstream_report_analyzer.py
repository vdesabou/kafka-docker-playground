def _html_deltas(deltas: List[dict]) -> str:
    rows = []
    for d in deltas:
        span = f"{os.path.basename(d['from'])} → {os.path.basename(d['to'])} ({_fmt_seconds(d['seconds'])})"
        for c in d["captures"]:
            def fmt(k):
                v = c[k]
                return f"{_fmt_num(v['before'])} → {_fmt_num(v['after'])} (Δ {_fmt_num(v['delta'])})"
            note = "restarted, mines again from its applied SCN" if c["restarted"] and (c["captured_scn"]["delta"] or 0) < 0 \
                else "restarted" if c["restarted"] else "captured SCN did not move" if d["seconds"] and c["captured_scn"]["delta"] == 0 else ""
            rows.append([span, f"capture {c['name']}", fmt("captured_scn"), fmt("messages_captured"), fmt("latency_seconds"), note])
        for s in d["outbound_servers"]:
            v = s["lcrs_sent"]
            rows.append([span, f"outbound {s['name']}", " → ".join(str(x) for x in s["status"]),
                         f"{_fmt_num(v['before'])} → {_fmt_num(v['after'])} (Δ {_fmt_num(v['delta'])})", "", ""])
    return _table("📈 Between reports", ["Reports", "Component", "Captured SCN / status", "Messages captured / LCRs sent", "Latency (s)", "Note"], rows)


def html_report(analyses: List["Analysis"], deltas: List[dict]) -> str:
    title = "Oracle XStream diagnostics analysis — " + ", ".join(os.path.basename(a.r.path) for a in analyses)
    body = "<hr class='report-sep'>".join(_html_one(a) for a in reversed(analyses))
    return (f"<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'><title>{_e(title)}</title>{_HTML_CSS}</head>"
            f"<body><div class='page'>{_html_deltas(deltas)}{body}"
            "<div class='footer'>🛠️ Generated by playground analyze oracle-xstream-report (kafka-docker-playground) from orclcdc_diag.sql report(s)</div>"
            "</div></body></html>")


# ── main ──────────────────────────────────────────────────────────────────────

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+", help="orclcdc_diag HTML report(s)")
    ap.add_argument("--json", action="store_true", help="Output JSON")
    ap.add_argument("--top", type=int, default=10, metavar="N", help="Max rows per list (default: 10)")
    ap.add_argument("--html-out", metavar="PATH", help="Write a self-contained HTML report")
    ap.add_argument("--problem", metavar="TEXT", help="Problem statement (symptom, since when): matched against the report")
    args = ap.parse_args()

    reports = []
    for f in args.files:
        try:
            r = Report(f)
        except OSError as e:
            print(f"❌ cannot read {f}: {e}", file=sys.stderr)
            return 1
        if not r.is_diag_report():
            print(f"❌ {f} is not an orclcdc_diag.sql report (no 'Confluent Oracle XStream CDC Connector Diagnostics' title / tables)", file=sys.stderr)
            return 2
        reports.append(r)
    reports.sort(key=lambda r: r.generated or datetime.min)
    analyses = [Analysis(r, args.top).run() for r in reports]
    if args.problem and args.problem.strip():
        for a in analyses:
            a.problem = correlate_problem(a, parse_problem(args.problem.strip(), a.r.generated))
    deltas = compare(analyses)

    if args.json:
        out = {"reports": [a.to_dict() for a in analyses], "deltas": deltas}
        print(json.dumps(out if len(analyses) > 1 else {**out["reports"][0], "deltas": deltas}, indent=2, default=str, ensure_ascii=False))
        return 0
    for a in analyses:
        print_text(a, args.top)
    print_deltas(deltas)
    if args.html_out:
        with open(args.html_out, "w", encoding="utf-8") as fh:
            fh.write(html_report(analyses, deltas))
        print(f"HTML report: {args.html_out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
