def _svg_advice(advice: List[dict]) -> str:
    """Estimated spills per streams pool size (gv$streams_pool_advice), current size highlighted."""
    rows = [a for a in advice if a.get("size_mb") is not None]
    if not rows:
        return "<p>NOT PRESENT IN REPORT</p>"
    W, rowh, L = 560, 20, 120
    H = 10 + rowh * len(rows)
    mx = max((a.get("spill_count") or 0) for a in rows) or 1
    out = [f'<svg viewBox="0 0 {W} {H}" xmlns="http://www.w3.org/2000/svg">']
    for i, a in enumerate(rows):
        y = 5 + i * rowh
        v = a.get("spill_count") or 0
        w = (W - L - 80) * v / mx
        color = "#2563eb" if a.get("factor") == 1 else ("#dc2626" if v else "#16a34a")
        label = f"{_fmt_num(a['size_mb'])} MB" + (" (current)" if a.get("factor") == 1 else "")
        out.append(f'<text x="{L - 6}" y="{y + 13}" font-size="10" text-anchor="end">{_e(label)}</text>'
                   f'<rect x="{L}" y="{y + 3}" width="{max(1, w):.1f}" height="13" fill="{color}"/>'
                   f'<text x="{L + w + 5:.1f}" y="{y + 13}" font-size="10" fill="#475569">{_e(_fmt_num(v))} spills</text>')
    out.append("</svg>")
    return "".join(out)


