    # Open and long running transactions
    def transactions(self):
        out = {}
        for comp, section in (("capture", "Capture Process: Open transactions"), ("apply", "Apply: Open transactions")):
            rows = self.r.rows(section)
            large, long_ = [], []
            for r in rows:
                count = _num(_col(r, "Cumulative Message Count", "Total Message Count"))
                age = self.age_seconds(r.get("First Message Time"))
                if count is not None and count > LARGE_TXN_LCRS:
                    large.append({"xid": r.get("XID"), "messages": count, "first_message_time": r.get("First Message Time")})
                if age is not None and age > LONG_TXN_SECONDS:
                    long_.append({"xid": r.get("XID"), "open_for_seconds": age, "first_message_scn": r.get("First Message SCN")})
            out[comp] = {"open": len(rows), "large": large, "long": long_}
            if len(rows) > OPEN_TXN_WARN:
                self.add("CRITICAL" if len(rows) > OPEN_TXN_CRIT else "HIGH", section, f"{len(rows):,} open transactions in {comp}",
                         {"open transactions": len(rows)}, "B")
        # one finding per transaction, seen in capture and / or apply
        for kind, key, sort_key in (("large", "messages", lambda t: -t["messages"]), ("long", "open_for_seconds", lambda t: -t["open_for_seconds"])):
            merged = {}
            for comp in ("capture", "apply"):
                for t in out[comp][kind]:
                    m = merged.setdefault(t["xid"], dict(t, components=[]))
                    m["components"].append(comp)
                    m[key] = max(m[key], t[key])
            for t in sorted(merged.values(), key=sort_key)[:self.top]:
                where = " and ".join(t["components"])
                section = "Capture Process: Open transactions" if "capture" in t["components"] else "Apply: Open transactions"
                if kind == "large":
                    self.add("HIGH", section, f"Large transaction {t['xid']} open in {where}: {_fmt_num(t['messages'])} LCRs", t, "B",
                             "Identify the job that produces it: a large transaction is buffered, spilled and sent only at commit")
                else:
                    self.add("HIGH", section, f"Transaction {t['xid']} open in {where} for {_fmt_seconds(t['open_for_seconds'])}", t, "B",
                             "A long open transaction holds back the capture restart SCN: commit or roll it back")
        long_db = []
        # a transaction that started after every captured SCN does not hold the capture back (yet)
        captured = [_num(c.get("captured_scn")) for c in self.summary.get("captures", []) if _num(c.get("captured_scn"))]
        for r in self.r.rows("Miscellaneous: Long running transactions"):
            minutes = _num(r.get("Duration"))
            scnb, scnw = _num(r.get("Start SCNB")), _num(r.get("Start SCNW"))
            start_scn = int(scnw) * 2 ** 32 + int(scnb) if scnb is not None and scnw is not None else None
            long_db.append({"session": r.get("Session"), "xid": r.get("XID"), "status": r.get("Status"),
                            "minutes": minutes, "username": r.get("Username"), "program": r.get("Program"), "module": r.get("Module"),
                            "start_scn": start_scn,
                            "after_capture_position": bool(start_scn and captured and start_scn > max(captured))})
        for t in sorted(long_db, key=lambda t: -(t["minutes"] or 0))[:self.top]:
            mins = t["minutes"] or 0
            after = t["after_capture_position"]
            self.add("MEDIUM" if after or mins * 60 <= LONG_TXN_SECONDS else "HIGH", "Miscellaneous: Long running transactions",
                     f"Database transaction {t['xid']} ({t['username']}, {t['program']}) running for {_fmt_seconds(mins * 60)}"
                     + (": started after the captured SCN, it is not what holds the capture position" if after else ""), t, "B")
        out["database_long_running"] = long_db
        self.summary["transactions"] = out

    # Rules: scope and overlapping captures
    def rules(self):
        scope = {}
        for r in self.r.rows("Rules: Capture process"):
            cap = r.get("Capture Name")
            kind = r.get("Streams Rule Type") or ""
            obj = ".".join(x for x in (r.get("Schema Name"), r.get("Object Name")) if x) or "(global)"
            entry = scope.setdefault(cap, {"tables": set(), "schemas": set(), "global": False, "ddl": False})
            if kind == "TABLE":
                entry["tables"].add(obj)
            elif kind == "SCHEMA":
                entry["schemas"].add(r.get("Schema Name"))
            elif kind == "GLOBAL":
                entry["global"] = True
            if (r.get("Rule Type") or "") == "DDL":
                entry["ddl"] = True
        self.summary["capture_rules"] = {k: {"tables": sorted(v["tables"]), "schemas": sorted(v["schemas"]),
                                             "global": v["global"], "ddl": v["ddl"]} for k, v in scope.items()}
        for cap, v in scope.items():
            if v["global"]:
                self.add("MEDIUM", "Rules: Capture process", f"Capture {cap} has a GLOBAL rule: every change of the database is captured",
                         {"Streams Rule Type": "GLOBAL"})
        caps = list(scope)
        for i, a in enumerate(caps):
            for b in caps[i + 1:]:
                sa, sb = scope[a], scope[b]
                common = (sa["tables"] & sb["tables"]) | {f"{s}.*" for s in sa["schemas"] & sb["schemas"]}
                common |= {t for t in sa["tables"] if t.split(".")[0] in sb["schemas"]}
                common |= {t for t in sb["tables"] if t.split(".")[0] in sa["schemas"]}
                if sa["global"] or sb["global"] or common:
                    self.add("HIGH", "Rules: Capture process", f"Captures {a} and {b} capture the same objects",
                             {"overlap": sorted(common)[:self.top] or ["GLOBAL rule"]}, "F",
                             "Each table should be captured by one capture process only")

