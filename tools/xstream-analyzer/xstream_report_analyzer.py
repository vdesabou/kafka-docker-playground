    # Outbound server
    def outbound(self):
        general = self.r.rows("Outbound Server: General")
        stats = {r.get("Outbound Name"): r for r in self.r.rows("Outbound Server: Statistics")}
        progress = {r.get("Outbound Name"): r for r in self.r.rows("Outbound Server: Progress")}
        servers = []
        if self.r.has_section("Outbound Server: General") and not general:
            self.add("CRITICAL", "Outbound Server: General", "No XStream outbound server in the database", None, "H")
        for g in general:
            name = g.get("Outbound Name")
            s, p = stats.get(name, {}), progress.get(name, {})
            last_sent = s.get("Last Sent LCR Time")
            idle = self.age_seconds(last_sent)
            srv = {"name": name, "status": g.get("Status"), "connect_user": g.get("Connect User"), "capture": g.get("Capture Name"),
                   "state": s.get("State"), "transactions_sent": _num(s.get("Total Transactions Sent")),
                   "lcrs_sent": _num(s.get("Total LCRs Sent")), "last_sent_lcr_time": last_sent,
                   "last_sent_lcr_scn": s.get("Last Sent LCR SCN"), "seconds_since_last_sent": idle,
                   "processed_low_scn": p.get("Process Low SCN"), "oldest_scn": p.get("Oldest SCN")}
            servers.append(srv)
            st = (srv["status"] or "").upper()
            if st == "DETACHED":
                self.add("HIGH", "Outbound Server: General", f"Outbound server {name} is DETACHED: no connector task is attached",
                         {"Status": srv["status"]}, "D", "Check the connector status and logs (playground connector status, playground container logs -c connect --errors)")
            elif st and st not in ("ATTACHED",):
                self.add("MEDIUM", "Outbound Server: General", f"Outbound server {name} status is {srv['status']}", {"Status": srv["status"]})
            if st == "ATTACHED" and idle is not None and idle > OUTBOUND_IDLE_SECONDS:
                caps = [c for c in self.summary.get("captures", []) if c["name"] == srv["capture"]]
                # nothing to send: the capture has no backlog (low latency, or waiting for redo)
                cap_idle = bool(caps) and not caps[0].get("stuck") and ((caps[0].get("state") or "").startswith("WAITING FOR REDO")
                                           or (caps[0].get("latency_seconds") is not None and caps[0]["latency_seconds"] <= LATENCY_WARN))
                self.add("INFO" if cap_idle else "MEDIUM", "Outbound Server: Statistics",
                         f"Outbound server {name} sent its last LCR {_fmt_seconds(idle)} before the report"
                         + (" (capture has no backlog: no captured change to send)" if cap_idle else " while ATTACHED and the capture lags"),
                         {"Last Sent LCR Time": last_sent, "Report time": str(self.r.generated), "Total LCRs Sent": _fmt_num(srv["lcrs_sent"])})
        self.summary["outbound_servers"] = servers

    # Apply (outbound server apply components)
    def apply(self):
        status = self.r.rows("Apply: Status")
        for r in status:
            st = r.get("Status")
            if st and st != "ENABLED":
                err = _error(r.get("Error Number"), r.get("Error Message"))
                self.add("CRITICAL", "Apply: Status", f"Apply {r.get('Apply Name')} is {st}" + (f": {err}" if err else ""),
                         {"Status": st, "Error Number": r.get("Error Number"), "Error Message": r.get("Error Message")}, "H",
                         f"Fix the error, then EXEC DBMS_XSTREAM_ADM.START_OUTBOUND('{r.get('Apply Name')}');")
        readers = []
        for r in self.r.rows("Apply Reader: Statistics"):
            name = r.get("Apply Name")
            latency = _num(r.get("Reader Latency (seconds)"))
            spilled = _num(r.get("Total Messages Spilled"))
            rd = {"apply": name, "state": r.get("State"), "dequeued": _num(r.get("Total Messages Dequeued")),
                  "spilled": spilled, "latency_seconds": latency, "sga_used_mb": _num(r.get("SGA Used (MB)")),
                  "sga_allocated_mb": _num(r.get("SGA Allocated (MB)")), "in_memory_lcrs": _num(r.get("Total In-Memory LCRs"))}
            readers.append(rd)
            detached = any(srv["name"] == name and (srv["status"] or "").upper() == "DETACHED" for srv in self.summary.get("outbound_servers", []))
            if latency is not None and latency > LATENCY_WARN:
                if detached:
                    self.add("INFO", "Apply Reader: Statistics",
                             f"Apply reader of {name} latency is {_fmt_seconds(latency)}: consequence of the DETACHED outbound server",
                             {"Reader Latency (seconds)": _fmt_num(latency), "State": rd["state"]}, "D")
                else:
                    self.add("CRITICAL" if latency > LATENCY_CRIT else "HIGH", "Apply Reader: Statistics",
                             f"Apply reader of {name} latency is {_fmt_seconds(latency)}",
                             {"Reader Latency (seconds)": _fmt_num(latency), "State": rd["state"]})
            rd["txn_lcr_spill_threshold"] = self.apply_param(name, "TXN_LCR_SPILL_THRESHOLD")
            rd["txn_age_spill_threshold"] = self.apply_param(name, "TXN_AGE_SPILL_THRESHOLD")
            used = rd["sga_used_mb"]
            max_sga = self.max_sga("Apply: Parameters", "Apply Name", name)
            if used is not None and max_sga and used * 100 / max_sga > SGA_USED_CRIT:
                self.add("HIGH", "Apply Reader: Statistics", f"Apply reader of {name} uses {used * 100 / max_sga:.0f}% of its MAX_SGA_SIZE",
                         {"SGA Used (MB)": _fmt_num(used), "MAX_SGA_SIZE (MB)": _fmt_num(max_sga)}, "A",
                         f"EXEC DBMS_XSTREAM_ADM.SET_PARAMETER('{name}', 'max_sga_size', '<MB>'); and size streams_pool_size accordingly")
        self.summary["apply_readers"] = readers
        # transactions above TXN_LCR_SPILL_THRESHOLD (LCRs) or TXN_AGE_SPILL_THRESHOLD (seconds) are spilled by design
        spilled_txns = self.r.rows("Apply: Spilled transactions")
        by_design, unexpected = [], []
        for t in spilled_txns:
            name = t.get("Apply Name")
            lcr_threshold = self.apply_param(name, "TXN_LCR_SPILL_THRESHOLD") or 10000
            age_threshold = self.apply_param(name, "TXN_AGE_SPILL_THRESHOLD") or 900
            count = _num(t.get("Spilled Messages")) or 0
            age = self.age_seconds(t.get("First Message Create Time"))
            (by_design if count >= lcr_threshold or (age is not None and age >= age_threshold) else unexpected).append(t)
        if by_design:
            total = sum(_num(t.get("Spilled Messages")) or 0 for t in by_design)
            largest = max(by_design, key=lambda t: _num(t.get("Spilled Messages")) or 0)
            self.add("MEDIUM", "Apply: Spilled transactions",
                     f"{len(by_design)} transaction(s) spilled to disk ({_fmt_num(total)} LCRs) because they exceed TXN_LCR_SPILL_THRESHOLD "
                     "or TXN_AGE_SPILL_THRESHOLD: expected for large or long transactions, it slows them down",
                     {"largest XID": largest.get("XID"), "Spilled Messages": largest.get("Spilled Messages"),
                      "First Message Create Time": largest.get("First Message Create Time")}, "B")
        if unexpected:
            total = sum(_num(t.get("Spilled Messages")) or 0 for t in unexpected)
            self.add("HIGH", "Apply: Spilled transactions",
                     f"{len(unexpected)} transaction(s) below the spill thresholds spilled to disk ({_fmt_num(total)} LCRs): memory pressure",
                     {"XIDs": ", ".join(t.get("XID") or "" for t in unexpected[:self.top])}, "A",
                     "Raise streams_pool_size (see Streams Pool: Size advice) or the outbound MAX_SGA_SIZE")
        for rd in readers:
            explained = sum(_num(t.get("Spilled Messages")) or 0 for t in by_design if t.get("Apply Name") == rd["apply"])
            if rd["spilled"] and rd["spilled"] > explained:
                self.add("MEDIUM", "Apply Reader: Statistics",
                         f"Apply reader of {rd['apply']} spilled {_fmt_num(rd['spilled'] - explained)} messages that no large or long transaction explains",
                         {"Total Messages Spilled": _fmt_num(rd["spilled"]), "spilled by large / long transactions": _fmt_num(explained)}, "A")
        self.summary["apply_servers"] = [{"apply": r.get("Apply Name"), "server": r.get("Parallel Server Number"),
                                          "state": r.get("State"), "xid": r.get("XID")} for r in self.r.rows("Apply Server: Statistics")]

