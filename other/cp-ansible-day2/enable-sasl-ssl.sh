#!/bin/bash
set -e
DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null && pwd )"
source ${DIR}/../../scripts/utils.sh
source ${DIR}/day2-utils.bash

# PLAINTEXT -> SASL_SSL on a running cluster deployed by cp-ansible, in the 3 steps of a migration without downtime:
#   1. add a SASL_SSL listener next to PLAINTEXT (rolling): nothing changes for the clients
#   2. move the clients to it: connect and schema registry (<component>_kafka_listener_name), the producer
#   3. close PLAINTEXT (the internal listener becomes SASL_SSL, rolling)
# A second producer is never moved: it shows what a forgotten client sees at step 3, the classic mistake.
# The inter-broker listener (BROKER, 9091) stays as it is: changing it in one rolling run breaks the replication between
# the brokers already restarted and the others (a separate migration).
day2_require_plaintext

log "Step 1: a PLAINTEXT cluster deployed by cp-ansible, 1 controller, 3 brokers, schema registry, connect"
ENABLE_KAFKA_NODES=1 playground start-environment --environment ansible --docker-compose-override-file "${DIR}/docker-compose.plaintext.yml"
playground container get-properties -c broker | grep -E "^(listeners|listener.security.protocol.map)="
day2_start_workload
day2_start_producer 9092 "" legacy
sleep 10
day2_report_workload "before the migration" legacy

log "Step 2: add a SASL_SSL listener on 9093 next to PLAINTEXT, rolling (certificates generated by cp-ansible)"
playground ansible inventory set .all.vars.kafka_broker_custom_listeners '{"client": {"name": "CLIENT", "port": 9093, "ssl_enabled": true, "sasl_protocol": "plain"}}'
errors_before=$(day2_send_errors)
legacy_errors_before=$(day2_send_errors legacy)
playground ansible playbook --rolling
playground container get-properties -c broker | grep -E "^(listeners|listener.security.protocol.map)="
day2_report_workload "after adding the listener"
day2_report_workload "after adding the listener" legacy
errors_step2=$(( $(day2_send_errors) - errors_before ))
legacy_errors_step2=$(( $(day2_send_errors legacy) - legacy_errors_before ))

log "Step 3: move the clients to the SASL_SSL listener: connect and schema registry, then the producer"
playground ansible inventory set .all.vars.kafka_connect_kafka_listener_name client
playground ansible inventory set .all.vars.schema_registry_kafka_listener_name client
playground ansible playbook --rolling --limit kafka_connect,schema_registry
playground container get-properties -c connect | grep -E "^(bootstrap.servers|security.protocol|sasl.mechanism)="
# the producer: the client settings of the connect worker (SASL_SSL, truststore), written by the hand-over of the playbook
playground container exec -c connect --command "grep -v jaas /etc/kafka/client.properties"
day2_stop_producer producer
day2_start_producer 9093 /etc/kafka/client.properties producer
sleep 15
day2_report_workload "on the SASL_SSL listener"
playground connector status --connector day2-sink

log "Step 4: close PLAINTEXT: the internal listener (9092) becomes SASL_SSL, rolling"
playground ansible inventory set .all.vars.kafka_broker_custom_listeners.internal '{"ssl_enabled": true, "sasl_protocol": "plain"}'
errors_before=$(day2_send_errors)
legacy_errors_before=$(day2_send_errors legacy)
playground ansible playbook --rolling
playground container get-properties -c broker | grep -E "^(listeners|listener.security.protocol.map)="
errors_step4=$(( $(day2_send_errors) - errors_before ))
day2_report_workload "after closing PLAINTEXT"
# the forgotten client fails once every broker is restarted: its sends wait for metadata (max.block.ms, 60 s by default)
for i in $(seq 1 24)
do
    legacy_acks=$(day2_acks_since $(( $(day2_now) - 20000 )) legacy)
    if [ "$legacy_acks" == "0" ]
    then
        break
    fi
    sleep 5
done
day2_report_workload "after closing PLAINTEXT (never moved to SASL_SSL)" legacy
log "💥 the forgotten client: acks in the last 20 seconds: $legacy_acks, what it logs once PLAINTEXT is closed:"
playground container exec -c connect --command "grep -E 'WARN|ERROR|OutOfMemoryError' /tmp/day2-legacy.log | grep -v producer_send | tail -4"
if docker exec connect grep -q "OutOfMemoryError" /tmp/day2-legacy.log
then
    log "💥 java.lang.OutOfMemoryError in the network thread of a PLAINTEXT client talking to a TLS listener: it reads the first bytes of the TLS handshake as the size of a response (KAFKA-4090). The symptom customers report as 'our producers run out of memory after we enabled TLS'"
fi
day2_stop_producer legacy

log "Step 5: the playground commands follow the security of the cluster"
playground topic consume -t "$DAY2_TOPIC" --max-messages 3

log "Step 6: no record lost"
day2_check_no_loss
log "📋 send errors of the migrated producer: adding the listener $errors_step2, closing PLAINTEXT $errors_step4"
log "📋 send errors of the forgotten producer while adding the listener: $legacy_errors_step2; acks in the last 20 seconds once PLAINTEXT was closed: $legacy_acks"
if [ "$legacy_acks" != "0" ]
then
    logerror "❌ the forgotten PLAINTEXT client should not be able to produce once PLAINTEXT is closed ($legacy_acks acks in the last 20 seconds)"
    exit 1
fi
